def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    bidi.set(qn("w:val"), "1")
    pPr.append(bidi)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT

def add_p(text, size=11, bold=False, color=None, align=WD_ALIGN_PARAGRAPH.RIGHT,
          space_after=6, rtl=True, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    r.font.name = "Segoe UI"
    if color:
        r.font.color.rgb = color
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if rtl:
        set_rtl(p)
    return p

def add_h(text, level=1, color=NAVY, rtl=True):
    sizes = {1: 20, 2: 15, 3: 12.5}
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(sizes[level])
    r.font.bold = True
    r.font.color.rgb = color
    r.font.name = "Segoe UI"
    p.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    p.paragraph_format.space_after = Pt(6)
    if rtl:
        set_rtl(p)
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    if level == 1:
        pPr = p._p.get_or_add_pPr()
        pbdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "12")
        bottom.set(qn("w:color"), "C9A227")
        bottom.set(qn("w:space"), "4")
        pbdr.append(bottom)
        pPr.append(pbdr)
    return p

def add_bullet(text, color=None, bold_prefix=None):
    p = doc.add_paragraph(style="List Bullet")
    if bold_prefix:
        r0 = p.add_run(bold_prefix)
        r0.font.bold = True
        r0.font.size = Pt(11)
        r0.font.name = "Segoe UI"
        if color:
            r0.font.color.rgb = color
    r = p.add_run(text)
    r.font.size = Pt(11)
    r.font.name = "Segoe UI"
    if color and not bold_prefix:
        r.font.color.rgb = color
    set_rtl(p)
    p.paragraph_format.space_after = Pt(4)
    return p

def shade_cell(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)

def add_table(headers, rows, header_fill="0E2A47", widths=None, rtl=True):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        r = p.add_run(h)
        r.font.bold = True
        r.font.size = Pt(10.5)
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        r.font.name = "Segoe UI"
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        shade_cell(hdr[i], header_fill)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            r = p.add_run(str(v))
            r.font.size = Pt(10.5)
            r.font.name = "Segoe UI"
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if ri % 2 == 1:
                shade_cell(cells[i], "F2F5FA")
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    if rtl:
        tbl = t._tbl
        tblPr = tbl.tblPr
        bidi = OxmlElement("w:bidi")
        bidi.set(qn("w:val"), "1")
        tblPr.append(bidi)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t

def callout(title, body, fill="FFF6DD", tcolor=GOLD):
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    c = t.rows[0].cells[0]
    shade_cell(c, fill)
    c.text = ""
    p = c.paragraphs[0]
    r = p.add_run(title)
    r.font.bold = True
    r.font.size = Pt(11.5)
    r.font.color.rgb = tcolor
    r.font.name = "Segoe UI"
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(p)
    p2 = c.add_paragraph()
    r2 = p2.add_run(body)
    r2.font.size = Pt(10.5)
    r2.font.name = "Segoe UI"
    p2.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(p2)
    tblPr = t._tbl.tblPr
    bidi = OxmlElement("w:bidi")
    bidi.set(qn("w:val"), "1")
    tblPr.append(bidi)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)

